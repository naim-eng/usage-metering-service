import assert from "node:assert/strict";
import { test } from "node:test";
import { hashPassword as legacyHashPassword } from "@better-auth/utils/password";
import {
  hashCustomerPassword,
  verifyCustomerPassword,
} from "./password-crypto";

const password = "Synthetic credential testing passphrase!";

test("generates the expected versioned hash format", async () => {
  const hash = await hashCustomerPassword(password);

  assert.equal(
    /^scrypt-v1:[0-9a-f]{32}:[0-9a-f]{128}$/.test(hash),
    true
  );
});

test("does not store plaintext passwords", async () => {
  const hash = await hashCustomerPassword(password);

  assert.equal(hash.includes(password), false);
});

test("verifies the correct password", async () => {
  const hash = await hashCustomerPassword(password);

  assert.equal(
    await verifyCustomerPassword({ hash, password }),
    true
  );
});

test("rejects an incorrect password", async () => {
  const hash = await hashCustomerPassword(password);

  assert.equal(
    await verifyCustomerPassword({
      hash,
      password: password + "-incorrect",
    }),
    false
  );
});

test("generates distinct salts for identical passwords", async () => {
  const first = await hashCustomerPassword(password);
  const second = await hashCustomerPassword(password);

  assert.equal(first !== second, true);

  assert.equal(
    first.split(":")[1] !== second.split(":")[1],
    true
  );

  assert.equal(
    await verifyCustomerPassword({ hash: first, password }),
    true
  );

  assert.equal(
    await verifyCustomerPassword({ hash: second, password }),
    true
  );
});

test("preserves password whitespace", async () => {
  const hash = await hashCustomerPassword(" " + password + " ");

  assert.equal(
    await verifyCustomerPassword({
      hash,
      password: " " + password + " ",
    }),
    true
  );

  assert.equal(
    await verifyCustomerPassword({ hash, password }),
    false
  );
});

test("preserves case sensitivity", async () => {
  const hash = await hashCustomerPassword(password);

  assert.equal(
    await verifyCustomerPassword({
      hash,
      password: password.toLowerCase(),
    }),
    false
  );
});

test("preserves existing Unicode normalization behavior", async () => {
  const composed = "Synthetic caf\u00e9 passphrase";
  const decomposed = "Synthetic cafe\u0301 passphrase";

  const hash = await hashCustomerPassword(composed);

  assert.equal(
    await verifyCustomerPassword({
      hash,
      password: decomposed,
    }),
    true
  );
});

test("verifies hashes generated by the original Better Auth implementation", async () => {
  const hash = await legacyHashPassword(password);

  assert.equal(
    /^[0-9a-f]{32}:[0-9a-f]{128}$/.test(hash),
    true
  );

  assert.equal(
    await verifyCustomerPassword({ hash, password }),
    true
  );
});

test("rejects incorrect passwords against legacy hashes", async () => {
  const hash = await legacyHashPassword(password);

  assert.equal(
    await verifyCustomerPassword({
      hash,
      password: password + "-incorrect",
    }),
    false
  );
});

test("preserves legacy passwords below the new minimum length", async () => {
  const legacyPassword = "Legacy1!";
  const hash = await legacyHashPassword(legacyPassword);

  assert.equal(
    await verifyCustomerPassword({
      hash,
      password: legacyPassword,
    }),
    true
  );
});

test("rejects unsupported hash versions", async () => {
  const hash = await hashCustomerPassword(password);

  assert.equal(
    await verifyCustomerPassword({
      hash: hash.replace("scrypt-v1:", "scrypt-v999:"),
      password,
    }),
    false
  );
});

test("rejects malformed stored hashes", async () => {
  const salt = "a".repeat(32);
  const key = "b".repeat(128);

  const malformedHashes = [
    "",
    "invalid",
    `${salt}:`,
    `:${key}`,
    `${salt}:${key}:extra`,
    `scrypt-v1:${salt}:${key}:extra`,
    `scrypt-v1:${salt.slice(1)}:${key}`,
    `scrypt-v1:${salt}:${key.slice(1)}`,
    `scrypt-v1:${"z".repeat(32)}:${key}`,
    `scrypt-v1:${salt}:${"z".repeat(128)}`,
    `scrypt-v1:${salt}:${key}00`,
    `scrypt-v1:${salt}:${key}\n`,
  ];

  for (const hash of malformedHashes) {
    assert.equal(
      await verifyCustomerPassword({ hash, password }),
      false
    );
  }
});

test("rejects a modified derived key", async () => {
  const hash = await hashCustomerPassword(password);
  const lastCharacter = hash.slice(-1);
  const replacement = lastCharacter === "0" ? "1" : "0";

  const modifiedHash = hash.slice(0, -1) + replacement;

  assert.equal(
    await verifyCustomerPassword({
      hash: modifiedHash,
      password,
    }),
    false
  );
});
